ROOT=Path(__file__).resolve().parents[1]
TEST=ROOT/"test"
DEFAULT_BATCH="b5ff25b9bae3461aafcc82880b62b69f"
SKIP_REASON="用户跳过 TC06-M01：不手动准备 20 个账号。多账号计数、最新答卷替换和答案分页交由 TC06-M01-AUTO 验证；页面可读性、图表和空均值展示未作人工判定。"


def digest(content):
    return hashlib.sha256(content).hexdigest()


def read_json(path):
    return json.loads(path.read_text("utf-8"))


def write_json(path,value):
    path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+"\n","utf-8")


def integrity_details(audit):
    before,after=audit["before"],audit["after"]
    added=sorted(after.keys()-before.keys())
    removed=sorted(before.keys()-after.keys())
    modified=sorted(k for k in before.keys() & after.keys() if before[k]!=after[k])
    def critical(path):
        path=path.replace(chr(92),"/")
        return (path.startswith(("survey_app/","static/")) or
                path in ("app.py","数据库设计/schemas.json","test/cases.json","test/READ_TEST.md","test/TEST_CASES.md") or
                path.endswith(".zip"))
    return {"unchanged":not (added or removed or modified),"added":added,"removed":removed,"modified":modified,
            "criticalChanges":[p for p in added+removed+modified if critical(p)],
            "interpretation":"Observed workspace changes; hashes cannot identify the author. Reference-document changes do not block reporting. Critical changes return exit code 2 after reporting."}


def protected_files():
    files=[]
    for base in [ROOT/"survey_app",ROOT/"static",ROOT/"数据库设计"]:
        files.extend(p for p in base.rglob("*") if p.is_file() and "__pycache__" not in p.parts)
    files.extend(ROOT.glob("*.pdf"))
    files.extend(ROOT.glob("*.md"))
    files.extend(ROOT.glob("*.py"))
    files.extend([TEST/"cases.json",TEST/"READ_TEST.md",TEST/"TEST_CASES.md"])
    files.extend(TEST.glob("*-results-*.zip"))
    return {str(p.relative_to(ROOT)):digest(p.read_bytes()) for p in files}


def import_manual(json_zip,allure_zip,results_dir,catalog):
    with zipfile.ZipFile(json_zip) as archive:
        source=json.loads(archive.read("actual-results.json"))
        snapshot=json.loads(archive.read("cases.json"))
        assert snapshot==catalog,"Manual export and current catalog differ; choose matching artifacts explicitly."
        assert source["source"]["sha256"]==digest((ROOT/source["source"]["path"]).read_bytes())
        for row in source["results"]:
            if row["execution"]=="manual":
                for item in row["attachments"]:
                    content=archive.read(item["path"])
                    assert len(content)==item["size"] and digest(content)==item["sha256"],"Manual evidence checksum mismatch"
    rows={r["caseId"]:copy.deepcopy(r) for r in source["results"] if r["execution"]=="manual"}
    manual_records=[]
    image_digests=[]
    with zipfile.ZipFile(allure_zip) as archive:
        for entry in archive.infolist():
            if entry.is_dir():
                continue
            # Exports generated by the collector are deliberately flat.
            assert Path(entry.filename).name==entry.filename and ":" not in entry.filename,"Unsafe ZIP member"
            if entry.filename.endswith("-result.json"):
                record=json.loads(archive.read(entry))
                labels={x["name"]:x["value"] for x in record["labels"]}
                cid=labels["caseId"]
                assert cid in rows and labels["execution"]=="manual"
                row=rows[cid]
                assert labels["manualStatus"]==row["status"]
                expected=row["status"] if row["status"] in ("passed","failed") else "skipped"
                assert record["status"]==expected,"Manual status differs between exports"
                observations=[a for a in record.get("attachments",[]) if a["name"]=="实际结果"]
                assert len(observations)==1
                observation=json.loads(archive.read(observations[0]["source"]))
                assert observation.get("actual","")==row["actual"],"Manual observations differ between exports"
                for item in record.get("attachments",[]):
                    content=archive.read(item["source"])
                    if item["type"].startswith("image/"):
                        image_digests.append(digest(content))
                    target=results_dir/item["source"]
                    assert not target.exists(),"Attachment filename collision"
                    target.write_bytes(content)
                row["attachments"]=copy.deepcopy(record.get("attachments",[]))
                if cid=="TC06-M01" and row["status"]=="not_run":
                    row["originalStatus"]="not_run"
                    row["status"]="skipped"
                    row["actual"]=SKIP_REASON
                    record["status"]="skipped"
                    record["statusDetails"]={"message":SKIP_REASON,"trace":"原导出状态 not_run；仅合并副本按用户指示记为 skipped。"}
                    record["labels"]=[x for x in record["labels"] if x["name"]!="manualStatus"]+[
                        {"name":"manualStatus","value":"skipped"},{"name":"originalManualStatus","value":"not_run"}]
                    extra=uuid.uuid4().hex+"-attachment.json"
                    write_json(results_dir/extra,{"reason":SKIP_REASON,"originalStatus":"not_run","derivedStatus":"skipped"})
                    record["attachments"].append({"name":"用户跳过说明","source":extra,"type":"application/json"})
                write_json(results_dir/entry.filename,record)
                manual_records.append(record)
    assert len(manual_records)==len(rows) and len({r["uuid"] for r in manual_records})==len(rows)
    expected_images=[a["sha256"] for r in source["results"] if r["execution"]=="manual" for a in r["attachments"]]
    assert Counter(image_digests)==Counter(expected_images),"Screenshot evidence differs between manual exports"
    write_json(results_dir/"manual-summary-original.json",source)
    write_json(results_dir/"manual-summary.json",{"sourceRun":source["run"],"summary":dict(Counter(r["status"] for r in rows.values())),"results":list(rows.values())})
    return source,list(rows.values())


def attachments(record):
    for item in record.get("attachments",[]):
        yield item
    for step in record.get("steps",[]):
        yield from attachments(step)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manual-json",type=Path,default=TEST/f"manual-results-{DEFAULT_BATCH}.zip")
    parser.add_argument("--manual-allure",type=Path,default=TEST/f"allure-results-{DEFAULT_BATCH}.zip")
    parser.add_argument("--allure",default=shutil.which("allure") or shutil.which("allure.bat"))
    parser.add_argument("--mongo-uri",default=os.getenv("MONGODB_URI","mongodb://127.0.0.1:27018/?replicaSet=survey-rs"))
    parser.add_argument("--keep-database",action="store_true",help="Keep only this run's random questionnaire_test_* DB for diagnosis")
    parser.add_argument("--resume",type=Path,help="Rebuild report from a completed existing run without rerunning API tests")
    args=parser.parse_args()
    if not args.allure:
        parser.error("Allure CLI not found; add it to PATH or use --allure D:\\allure-2.45.0\\bin\\allure.bat")
    if args.resume:
        folder=args.resume.resolve()
        if folder.parent != (TEST/"runs").resolve():
            parser.error("--resume must select a directory directly inside test/runs")
        source=read_json(folder/"allure-results/manual-summary-original.json")
        manual=read_json(folder/"allure-results/manual-summary.json")["results"]
        catalog=read_json(TEST/"cases.json")
        assert source["catalogVersion"]==catalog["catalogVersion"]
        records=[read_json(p) for p in (folder/"allure-results").glob("*-result.json")]
        api=[r for r in records if any(x["name"]=="execution" and x["value"]=="api" for x in r.get("labels",[]))]
        assert "[100%]" in (folder/"pytest.log").read_text("utf-8") and len(api)==130, "Incomplete execution cannot be recovered"
        provenance={"manualRunId":source["run"]["id"],"catalogVersion":catalog["catalogVersion"],
                    "changes":SKIP_REASON,"reportRecoveredFrom":str(folder),"apiRerun":False}
        return finalize(args,folder,catalog,source,manual,provenance,
                        1 if any(r["status"] in ("failed","broken") for r in api) else 0)
    for package in ["pytest","allure_pytest","requests"]:
        __import__(package)
    # Verify environment before collecting tests; never convert unavailable MongoDB into passes.
    from pymongo import MongoClient
    with MongoClient(args.mongo_uri,serverSelectionTimeoutMS=5000) as client:
        hello=client.admin.command("hello")
        assert hello.get("setName") and hello.get("isWritablePrimary"),"A primary MongoDB replica set is required"
    catalog=read_json(TEST/"cases.json")
    before=protected_files()
    run_id=datetime.now().strftime("%Y%m%d-%H%M%S")+"-"+uuid.uuid4().hex[:6]
    folder=TEST/"runs"/run_id
    results=folder/"allure-results";results.mkdir(parents=True)
    report=folder/"allure-report"
    source,manual=import_manual(args.manual_json,args.manual_allure,results,catalog)
    provenance={"manualJsonZip":{"path":str(args.manual_json.resolve()),"sha256":digest(args.manual_json.read_bytes())},
                "manualAllureZip":{"path":str(args.manual_allure.resolve()),"sha256":digest(args.manual_allure.read_bytes())},
                "manualRunId":source["run"]["id"],"catalogVersion":catalog["catalogVersion"],"changes":SKIP_REASON}
    env=os.environ.copy()
    env["MONGODB_URI"]=args.mongo_uri
    env["API_RUNTIME_JSON"]=str(folder/"runtime.json")
    env["PYTHONIOENCODING"]="utf-8"
    env.pop("KEEP_TEST_DATABASE",None)
    if args.keep_database:
        env["KEEP_TEST_DATABASE"]="1"
    command=[sys.executable,"-X","utf8","-m","pytest","test/api","-q","--tb=short","--alluredir",str(results)]
    print("Running 129 API catalog scenarios + 1 multi-account supplement on a random isolated database.",flush=True)
    with (folder/"pytest.log").open("w",encoding="utf-8") as log:
        process=subprocess.Popen(command,cwd=ROOT,env=env,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True,encoding="utf-8",errors="replace")
        for line in process.stdout:
            print(line,end="",flush=True);log.write(line)
        pytest_code=process.wait()
    return finalize(args,folder,catalog,source,manual,provenance,pytest_code,before)


def finalize(args,folder,catalog,source,manual,provenance,pytest_code,before=None):
    run_id=folder.name
    results=folder/"allure-results"
    report=folder/"allure-report"
    api=[]
    titles={c["id"]:c["title"] for c in catalog["cases"]}
    titles["TC06-M01-AUTO"]="21 个账号的统计与答案分页（补充，未验证页面）"
    fixture_evidence={}
    for path in results.glob("*-container.json"):
        container=read_json(path)
        evidence=[]
        for phase in ("befores","afters"):
            for fixture in container.get(phase,[]):
                evidence.extend(attachments(fixture))
        for child in container.get("children",[]):
            fixture_evidence.setdefault(child,[]).extend(evidence)
    for path in results.glob("*-result.json"):
        record=read_json(path)
        labels={x["name"]:x["value"] for x in record.get("labels",[])}
        if labels.get("execution")!="api":
            continue
        cid=labels["caseId"]
        stable=digest(("questionnaire."+cid).encode())
        record.update(name=cid+" "+titles[cid],fullName="questionnaire."+cid,historyId=stable,testCaseId=stable)
        # Pytest yield-fixture attachments otherwise live only in Allure containers.
        # Also expose them directly on each case and in the combined actual JSON.
        direct=record.setdefault("attachments",[])
        known={a["source"] for a in direct}
        for item in fixture_evidence.get(record["uuid"],[]):
            if item["source"] not in known:
                direct.append(item);known.add(item["source"])
        write_json(path,record)
        api.append({"caseId":cid,"execution":"api","title":record["name"],"module":labels.get("suite"),
            "status":record["status"],"actual":record.get("statusDetails",{}).get("message","Assertions passed; HTTP and DB evidence attached"),
            "start":record.get("start"),"stop":record.get("stop"),"attachments":list(attachments(record))})
    expected={c["id"] for c in catalog["cases"] if c["execution"]=="api"}
    seen=[r["caseId"] for r in api]
    coverage={"specified":len(expected),"executedRecords":len(api),"missing":sorted(expected-set(seen)),
              "supplemental":sorted(set(seen)-expected),"duplicates":[k for k,v in Counter(seen).items() if v>1]}
    records=[read_json(p) for p in results.glob("*-result.json")]
    containers=[read_json(p) for p in results.glob("*-container.json")]
    for record in records+containers:
        for item in attachments(record):
            path=(results/item["source"]).resolve()
            assert path.parent==results.resolve() and path.is_file(),"Missing or unsafe Allure attachment"
        for phase in ("befores","afters"):
            for fixture in record.get(phase,[]):
                for item in attachments(fixture):
                    path=(results/item["source"]).resolve()
                    assert path.parent==results.resolve() and path.is_file(),"Missing fixture attachment"
    if before is not None:
        after=protected_files()
        audit={"unchanged":before==after,"before":before,"after":after}
        write_json(folder/"source-integrity.json",audit)
    else:
        audit=read_json(folder/"source-integrity.json")
    comparison=integrity_details(audit)
    write_json(folder/"integrity-assessment.json",comparison)
    write_json(results/"integrity-assessment.json",comparison)
    if not audit["unchanged"]:
        print("Workspace changes recorded; continuing report generation:",json.dumps(comparison,ensure_ascii=True),flush=True)
    counts={"manual":dict(Counter(r["status"] for r in manual)),"api":dict(Counter(r["status"] for r in api)),
            "allure":dict(Counter(r["status"] for r in records))}
    merged={"schemaVersion":1,"kind":"questionnaire-combined-test-results","runId":run_id,
            "generatedAt":datetime.now(timezone.utc).isoformat(),"provenance":provenance,"coverage":coverage,
            "summary":counts,"integrity":comparison,"pytestExitCode":pytest_code,"results":manual+sorted(api,key=lambda r:r["caseId"])}
    write_json(folder/"actual-results.json",merged)
    write_json(results/"provenance.json",provenance)
    write_json(results/"executor.json",{"name":"Local pytest + preserved manual evidence","type":"pytest","buildName":run_id})
    runtime=read_json(folder/"runtime.json") if (folder/"runtime.json").exists() else {}
    (results/"environment.properties").write_text("Mode=Real HTTP with isolated MongoDB\nDatabase="+runtime.get("database","startup-failed")+"\nManualRun="+source["run"]["id"]+"\n","utf-8")
    with zipfile.ZipFile(folder/"allure-results-combined.zip","w",zipfile.ZIP_DEFLATED) as archive:
        for path in results.iterdir():
            archive.write(path,path.name)
    generated=subprocess.run([args.allure,"generate",str(results),"--clean","-o",str(report)],cwd=ROOT)
    if generated.returncode==0:
        widget=read_json(report/"widgets/summary.json")["statistic"]
        assert widget["total"]==len(records),"Generated Allure report is missing test records"
        for state in ["passed","failed","broken","skipped"]:
            assert widget.get(state,0)==counts["allure"].get(state,0),"Allure status count mismatch"
        write_json(folder/"report-validation.json",{"verified":True,"allureStatistics":widget,"attachmentsVerified":True})
    latest={"runId":run_id,"directory":str(folder),"reportDirectory":str(report),"resultsDirectory":str(results),
            "summary":counts,"coverage":coverage,"pytestExitCode":pytest_code,"allureExitCode":generated.returncode}
    write_json(TEST/"latest-run.json",latest)
    print(json.dumps(latest,ensure_ascii=False,indent=2))
    print("Open report: python test/open_report.py")
    if coverage["missing"] or coverage["duplicates"] or comparison["criticalChanges"]:
        return 2
    return pytest_code or generated.returncode


if __name__=="__main__":
    raise SystemExit(main())
